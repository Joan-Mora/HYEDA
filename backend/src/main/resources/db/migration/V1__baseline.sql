-- =============================================================================
-- HYEDA v2 - Esquema base
--
-- SQL portable: corre igual en PostgreSQL y en H2 (modo PostgreSQL).
-- Por eso se usan CHECK sobre VARCHAR en lugar de tipos ENUM nativos, y
-- VARCHAR en lugar de JSONB/TEXT.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Identidad y control de acceso
-- -----------------------------------------------------------------------------
CREATE TABLE app_user (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             VARCHAR(80)  NOT NULL UNIQUE,
    password_hash        VARCHAR(255) NOT NULL,
    full_name            VARCHAR(150) NOT NULL,
    email                VARCHAR(120),
    phone                VARCHAR(40),
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login_at        TIMESTAMP,
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)   NOT NULL UNIQUE,
    description VARCHAR(400),
    system_role BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_permission (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(80)  NOT NULL UNIQUE,
    module      VARCHAR(80)  NOT NULL,
    description VARCHAR(400)
);

CREATE TABLE user_role (
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES app_role(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE role_permission (
    role_id       BIGINT NOT NULL REFERENCES app_role(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES app_permission(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE refresh_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    token_hash VARCHAR(120) NOT NULL UNIQUE,
    expires_at TIMESTAMP    NOT NULL,
    revoked    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_refresh_user ON refresh_token(user_id, revoked);

-- -----------------------------------------------------------------------------
-- 2. Clientes, reputacion y antecedentes
-- -----------------------------------------------------------------------------
CREATE TABLE customer (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document          VARCHAR(40)  NOT NULL UNIQUE,
    document_type     VARCHAR(20)  NOT NULL DEFAULT 'CC',
    name              VARCHAR(180) NOT NULL,
    phone             VARCHAR(40),
    email             VARCHAR(120),
    id_copy_path      VARCHAR(500),
    data_consent      BOOLEAN      NOT NULL DEFAULT FALSE,
    data_consent_at   TIMESTAMP,
    reputation_score  NUMERIC(8,2) NOT NULL DEFAULT 50.00,
    customer_type     VARCHAR(20)  NOT NULL DEFAULT 'NUEVO',
    rental_count      INTEGER      NOT NULL DEFAULT 0,
    notes             VARCHAR(4000),
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_customer_type CHECK (customer_type IN ('NUEVO', 'FRECUENTE', 'CONFIANZA', 'RESTRINGIDO')),
    CONSTRAINT chk_customer_document_type CHECK (document_type IN ('CC', 'CE', 'NIT', 'PASAPORTE'))
);

CREATE INDEX idx_customer_name ON customer(name);

CREATE TABLE customer_address (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT       NOT NULL REFERENCES customer(id) ON DELETE CASCADE,
    label       VARCHAR(40)  NOT NULL DEFAULT 'OBRA',
    address     VARCHAR(500) NOT NULL,
    reference   VARCHAR(200),
    lat         DOUBLE PRECISION,
    lng         DOUBLE PRECISION,
    maps_url    VARCHAR(700),
    is_default  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_address_label CHECK (label IN ('OBRA', 'RESIDENCIA', 'OFICINA'))
);

CREATE TABLE reputation_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT       NOT NULL REFERENCES customer(id) ON DELETE CASCADE,
    rental_id   BIGINT,
    event_type  VARCHAR(40)  NOT NULL,
    delta       NUMERIC(8,2) NOT NULL,
    score_after NUMERIC(8,2) NOT NULL,
    reason      VARCHAR(400),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_reputation_event CHECK (event_type IN
        ('DEVOLUCION_A_TIEMPO', 'PAGO_COMPLETO', 'MORA', 'DANIO', 'FALTANTE', 'ABONO', 'MANUAL'))
);

CREATE INDEX idx_reputation_customer ON reputation_event(customer_id, created_at);

CREATE TABLE background_check (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   BIGINT REFERENCES customer(id) ON DELETE SET NULL,
    document      VARCHAR(40)  NOT NULL,
    status        VARCHAR(30)  NOT NULL DEFAULT 'PENDIENTE_MANUAL',
    result        VARCHAR(4000),
    observations  VARCHAR(4000),
    provider      VARCHAR(80)  NOT NULL DEFAULT 'manual',
    evidence_path VARCHAR(500),
    checked_by    BIGINT REFERENCES app_user(id),
    checked_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_background_status CHECK (status IN
        ('PENDIENTE_MANUAL', 'SIN_ANTECEDENTES', 'CON_ANTECEDENTES', 'RECHAZADO', 'ENVIADO'))
);

CREATE INDEX idx_background_document ON background_check(document);

-- -----------------------------------------------------------------------------
-- 3. Inventario y concurrencia de stock
-- -----------------------------------------------------------------------------
CREATE TABLE product (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                 VARCHAR(40) UNIQUE,
    name                VARCHAR(200)  NOT NULL,
    description         VARCHAR(4000),
    category            VARCHAR(80),
    unit                VARCHAR(30)   NOT NULL DEFAULT 'UNIDAD',
    daily_price         NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (daily_price >= 0),
    late_fee_per_day    NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (late_fee_per_day >= 0),
    replacement_value   NUMERIC(14,2) NOT NULL DEFAULT 0,
    stock_total         INTEGER       NOT NULL DEFAULT 0 CHECK (stock_total >= 0),
    stock_available     INTEGER       NOT NULL DEFAULT 0 CHECK (stock_available >= 0),
    min_stock_threshold INTEGER       NOT NULL DEFAULT 1,
    active              BOOLEAN       NOT NULL DEFAULT TRUE,
    version             BIGINT        NOT NULL DEFAULT 0,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_stock_available_le_total CHECK (stock_available <= stock_total)
);

CREATE INDEX idx_product_name ON product(name);
CREATE INDEX idx_product_category ON product(category);

-- Libro mayor de stock: solo se agrega, nunca se modifica. Es la auditoria
-- de por que el disponible de un producto cambio.
CREATE TABLE stock_ledger (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT       NOT NULL REFERENCES product(id),
    rental_id     BIGINT,
    movement_type VARCHAR(30)  NOT NULL,
    quantity      INTEGER      NOT NULL,
    balance_after INTEGER      NOT NULL,
    note          VARCHAR(400),
    user_id       BIGINT REFERENCES app_user(id),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_stock_movement CHECK (movement_type IN
        ('IMPORTACION', 'AJUSTE', 'RESERVA', 'LIBERACION', 'DESPACHO', 'RETORNO', 'BAJA_POR_DANIO'))
);

CREATE INDEX idx_stock_ledger_product ON stock_ledger(product_id, created_at);

-- Reserva temporal de stock. Garantiza que dos alquileres simultaneos no
-- tomen la misma unidad: gana el que abrio el flujo primero (FIFO por created_at).
CREATE TABLE stock_reservation (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT      NOT NULL REFERENCES product(id),
    rental_id   BIGINT,
    session_key VARCHAR(80),
    quantity    INTEGER     NOT NULL CHECK (quantity > 0),
    expires_at  TIMESTAMP   NOT NULL,
    consumed    BOOLEAN     NOT NULL DEFAULT FALSE,
    released    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_reservation_active ON stock_reservation(product_id, consumed, released, expires_at);

-- -----------------------------------------------------------------------------
-- 4. Alquiler
-- -----------------------------------------------------------------------------
CREATE TABLE rental (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  VARCHAR(30)   NOT NULL UNIQUE,
    customer_id           BIGINT        NOT NULL REFERENCES customer(id),
    user_id               BIGINT REFERENCES app_user(id),
    status                VARCHAR(30)   NOT NULL DEFAULT 'BORRADOR',
    document_policy       VARCHAR(20)   NOT NULL DEFAULT 'CONTRATO',
    start_date            DATE          NOT NULL,
    end_date              DATE          NOT NULL,
    actual_return_date    DATE,
    estimated_days        INTEGER       NOT NULL CHECK (estimated_days > 0),
    actual_days           INTEGER,
    delivery_address      VARCHAR(500)  NOT NULL,
    delivery_reference    VARCHAR(200),
    delivery_lat          DOUBLE PRECISION,
    delivery_lng          DOUBLE PRECISION,
    delivery_maps_url     VARCHAR(700),
    hauling_enabled       BOOLEAN       NOT NULL DEFAULT FALSE,
    hauling_cost          NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (hauling_cost >= 0),
    discount_amount       NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    discount_reason       VARCHAR(400),
    items_subtotal        NUMERIC(14,2) NOT NULL DEFAULT 0,
    estimated_total       NUMERIC(14,2) NOT NULL DEFAULT 0,
    late_fee_total        NUMERIC(14,2) NOT NULL DEFAULT 0,
    incident_charge_total NUMERIC(14,2) NOT NULL DEFAULT 0,
    final_amount          NUMERIC(14,2),
    credit_applied        NUMERIC(14,2) NOT NULL DEFAULT 0,
    refund_amount         NUMERIC(14,2) NOT NULL DEFAULT 0,
    data_consent_accepted BOOLEAN       NOT NULL DEFAULT FALSE,
    signature_path        VARCHAR(500),
    notes                 VARCHAR(4000),
    closed_at             TIMESTAMP,
    created_at            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_rental_status CHECK (status IN
        ('BORRADOR', 'RESERVADO', 'DOCUMENTO_EMITIDO', 'EN_CURSO', 'DEVUELTO',
         'FACTURACION_FINAL', 'PENDIENTE_PAGO', 'CERRADO', 'CANCELADO')),
    CONSTRAINT chk_document_policy CHECK (document_policy IN ('CONTRATO', 'REMISION')),
    CONSTRAINT chk_rental_dates CHECK (end_date >= start_date),
    -- Un descuento siempre debe venir justificado.
    CONSTRAINT chk_discount_reason CHECK (
        discount_amount = 0 OR (discount_reason IS NOT NULL AND LENGTH(TRIM(discount_reason)) > 0)
    )
);

CREATE INDEX idx_rental_customer ON rental(customer_id);
CREATE INDEX idx_rental_status ON rental(status);
CREATE INDEX idx_rental_created ON rental(created_at);

ALTER TABLE stock_reservation
    ADD CONSTRAINT fk_reservation_rental FOREIGN KEY (rental_id) REFERENCES rental(id) ON DELETE SET NULL;
ALTER TABLE stock_ledger
    ADD CONSTRAINT fk_ledger_rental FOREIGN KEY (rental_id) REFERENCES rental(id) ON DELETE SET NULL;
ALTER TABLE reputation_event
    ADD CONSTRAINT fk_reputation_rental FOREIGN KEY (rental_id) REFERENCES rental(id) ON DELETE SET NULL;

CREATE TABLE rental_item (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id         BIGINT        NOT NULL REFERENCES rental(id) ON DELETE CASCADE,
    product_id        BIGINT        NOT NULL REFERENCES product(id),
    product_name      VARCHAR(200)  NOT NULL,
    quantity          INTEGER       NOT NULL CHECK (quantity > 0),
    quantity_returned INTEGER       NOT NULL DEFAULT 0,
    unit_price        NUMERIC(14,2) NOT NULL,
    late_fee_snapshot NUMERIC(14,2) NOT NULL DEFAULT 0,
    estimated_days    INTEGER       NOT NULL,
    actual_days       INTEGER,
    line_estimated    NUMERIC(14,2) NOT NULL DEFAULT 0,
    line_final        NUMERIC(14,2)
);

CREATE INDEX idx_rental_item_rental ON rental_item(rental_id);
CREATE INDEX idx_rental_item_product ON rental_item(product_id);

CREATE TABLE rental_extension (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id    BIGINT      NOT NULL REFERENCES rental(id) ON DELETE CASCADE,
    extra_days   INTEGER     NOT NULL CHECK (extra_days > 0),
    previous_end DATE        NOT NULL,
    new_end      DATE        NOT NULL,
    reason       VARCHAR(400),
    approved_by  BIGINT REFERENCES app_user(id),
    requested_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rental_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id   BIGINT      NOT NULL REFERENCES rental(id) ON DELETE CASCADE,
    from_status VARCHAR(30),
    to_status   VARCHAR(30) NOT NULL,
    note        VARCHAR(400),
    changed_by  BIGINT REFERENCES app_user(id),
    changed_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_status_history_rental ON rental_status_history(rental_id, changed_at);

CREATE TABLE return_incident (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id      BIGINT        NOT NULL REFERENCES rental(id) ON DELETE CASCADE,
    rental_item_id BIGINT REFERENCES rental_item(id) ON DELETE SET NULL,
    item_condition VARCHAR(30)   NOT NULL,
    quantity       INTEGER       NOT NULL DEFAULT 1 CHECK (quantity > 0),
    reason         VARCHAR(200)  NOT NULL,
    description    VARCHAR(4000),
    charge_amount  NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (charge_amount >= 0),
    evidence_path  VARCHAR(500),
    reported_by    BIGINT REFERENCES app_user(id),
    reported_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_incident_condition CHECK (item_condition IN
        ('DANIO', 'FALTANTE', 'INCONFORMIDAD', 'DESGASTE'))
);

CREATE INDEX idx_incident_rental ON return_incident(rental_id);

-- -----------------------------------------------------------------------------
-- 5. Pagos, cartera y saldo a favor
-- -----------------------------------------------------------------------------
CREATE TABLE payment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id        BIGINT        NOT NULL REFERENCES rental(id),
    payment_type     VARCHAR(20)   NOT NULL,
    amount           NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    amount_tendered  NUMERIC(14,2),
    change_given     NUMERIC(14,2) NOT NULL DEFAULT 0,
    status           VARCHAR(20)   NOT NULL DEFAULT 'PENDIENTE',
    reference        VARCHAR(120),
    provider         VARCHAR(40),
    provider_payload VARCHAR(4000),
    qr_content       VARCHAR(1000),
    note             VARCHAR(400),
    paid_at          TIMESTAMP,
    recorded_by      BIGINT REFERENCES app_user(id),
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_payment_type CHECK (payment_type IN ('EFECTIVO', 'QR', 'TRANSFERENCIA', 'REEMBOLSO', 'AJUSTE')),
    CONSTRAINT chk_payment_status CHECK (status IN ('PENDIENTE', 'CONFIRMADO', 'FALLIDO', 'ANULADO'))
);

CREATE INDEX idx_payment_rental ON payment(rental_id);
CREATE INDEX idx_payment_status ON payment(status, created_at);

CREATE TABLE debt (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT        NOT NULL REFERENCES customer(id),
    rental_id       BIGINT REFERENCES rental(id),
    original_amount NUMERIC(14,2) NOT NULL,
    balance         NUMERIC(14,2) NOT NULL CHECK (balance >= 0),
    due_date        DATE,
    overdue_days    INTEGER       NOT NULL DEFAULT 0,
    status          VARCHAR(20)   NOT NULL DEFAULT 'ABIERTA',
    last_notice_at  TIMESTAMP,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_debt_status CHECK (status IN ('ABIERTA', 'PARCIAL', 'PAGADA', 'VENCIDA', 'CONDONADA'))
);

CREATE INDEX idx_debt_customer ON debt(customer_id, status);

-- Saldo a favor: si el cliente pago de mas y devolvio antes, queda credito.
CREATE TABLE customer_credit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT        NOT NULL REFERENCES customer(id),
    rental_id   BIGINT REFERENCES rental(id),
    amount      NUMERIC(14,2) NOT NULL,
    reason      VARCHAR(400)  NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_credit_customer ON customer_credit(customer_id);

-- -----------------------------------------------------------------------------
-- 6. Documentos
-- -----------------------------------------------------------------------------
CREATE TABLE document_sequence (
    document_type VARCHAR(20) PRIMARY KEY,
    prefix        VARCHAR(10) NOT NULL,
    next_value    BIGINT      NOT NULL DEFAULT 1
);

CREATE TABLE generated_document (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id     BIGINT REFERENCES rental(id) ON DELETE SET NULL,
    customer_id   BIGINT REFERENCES customer(id) ON DELETE SET NULL,
    document_type VARCHAR(20)  NOT NULL,
    serial_number VARCHAR(40)  NOT NULL UNIQUE,
    file_path     VARCHAR(500) NOT NULL,
    title         VARCHAR(200),
    metadata_json VARCHAR(4000),
    signed        BOOLEAN      NOT NULL DEFAULT FALSE,
    signed_at     TIMESTAMP,
    generated_by  BIGINT REFERENCES app_user(id),
    generated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_generated_document_type CHECK (document_type IN
        ('CONTRATO', 'REMISION', 'DEVOLUCION', 'FACTURA', 'REPORTE'))
);

CREATE INDEX idx_document_rental ON generated_document(rental_id);
CREATE INDEX idx_document_customer ON generated_document(customer_id);
CREATE INDEX idx_document_type ON generated_document(document_type, generated_at);

-- -----------------------------------------------------------------------------
-- 7. Finanzas de la empresa
-- -----------------------------------------------------------------------------
CREATE TABLE financial_movement (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_type VARCHAR(20)   NOT NULL,
    amount        NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    description   VARCHAR(400),
    category      VARCHAR(80),
    movement_date DATE          NOT NULL,
    rental_id     BIGINT REFERENCES rental(id) ON DELETE SET NULL,
    payment_id    BIGINT REFERENCES payment(id) ON DELETE SET NULL,
    user_id       BIGINT REFERENCES app_user(id),
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_movement_type CHECK (movement_type IN ('INGRESO', 'GASTO'))
);

CREATE INDEX idx_movement_date ON financial_movement(movement_date);
CREATE INDEX idx_movement_payment ON financial_movement(payment_id);

-- -----------------------------------------------------------------------------
-- 8. Notificaciones (patron outbox: se persiste y luego se despacha)
-- -----------------------------------------------------------------------------
CREATE TABLE notification (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id         BIGINT REFERENCES rental(id) ON DELETE SET NULL,
    customer_id       BIGINT REFERENCES customer(id) ON DELETE SET NULL,
    channel           VARCHAR(30)   NOT NULL DEFAULT 'WHATSAPP',
    template_code     VARCHAR(80)   NOT NULL,
    recipient         VARCHAR(40)   NOT NULL,
    message           VARCHAR(4000) NOT NULL,
    media_path        VARCHAR(500),
    status            VARCHAR(20)   NOT NULL DEFAULT 'EN_COLA',
    attempts          INTEGER       NOT NULL DEFAULT 0,
    last_error        VARCHAR(1000),
    provider_response VARCHAR(4000),
    sent_at           TIMESTAMP,
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_notification_status CHECK (status IN ('EN_COLA', 'ENVIADA', 'FALLIDA', 'DESCARTADA'))
);

CREATE INDEX idx_notification_pending ON notification(status, created_at);

-- -----------------------------------------------------------------------------
-- 9. Importaciones, auditoria y parametros de empresa
-- -----------------------------------------------------------------------------
CREATE TABLE import_job (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type    VARCHAR(30)  NOT NULL,
    file_name   VARCHAR(255),
    format      VARCHAR(10)  NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',
    rows_total  INTEGER      NOT NULL DEFAULT 0,
    rows_ok     INTEGER      NOT NULL DEFAULT 0,
    rows_error  INTEGER      NOT NULL DEFAULT 0,
    error_log   VARCHAR(4000),
    started_by  BIGINT REFERENCES app_user(id),
    started_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP,
    CONSTRAINT chk_import_type CHECK (job_type IN ('PRODUCTOS', 'CLIENTES', 'MOVIMIENTOS', 'DEUDAS')),
    CONSTRAINT chk_import_format CHECK (format IN ('CSV', 'XLSX')),
    CONSTRAINT chk_import_status CHECK (status IN ('PENDIENTE', 'COMPLETADO', 'FALLIDO', 'PARCIAL'))
);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT REFERENCES app_user(id),
    username    VARCHAR(80),
    action      VARCHAR(80)  NOT NULL,
    entity_type VARCHAR(80)  NOT NULL,
    entity_id   BIGINT,
    detail      VARCHAR(4000),
    ip_address  VARCHAR(60),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_entity ON audit_log(entity_type, entity_id);
CREATE INDEX idx_audit_created ON audit_log(created_at);

